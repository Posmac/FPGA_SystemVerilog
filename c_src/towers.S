.section .text
.global _start

_start:
    # 1. Инициализируем указатель стека (в самый конец 64 КБ памяти)
    li sp, 0xFFF0

    # 2. Выделяем место в статической памяти под "стержни" (pegs)
    # Для простоты будем хранить размеры стержней (количество дисков на них)
    # в регистрах: s1 = стержень 0, s2 = стержень 1, s3 = стержень 2
    li s1, 4    # На старте у стержня 0 есть 4 диска
    li s2, 0    # Стержень 1 пуст
    li s3, 0    # Стержень 2 пуст

    # 3. Вызываем рекурсивную функцию towers
    # Аргументы:
    # a0 = количество дисков (4)
    # a1 = откуда (0 - стержень s1)
    # a2 = куда (2 - стержень s3)
    # a3 = вспомогательный (1 - стержень s2)
    li a0, 4
    li a1, 0
    li a2, 2
    li a3, 1
    jal ra, towers

    # 4. Проверка результата после завершения алгоритма
    # Все 4 диска должны оказаться на стержне 2 (s3 = 4), а остальные пустыми
    li t0, 4
    bne s3, t0, fail
    bne s1, zero, fail
    bne s2, zero, fail

pass:
    li gp, 1        # МАРКЕР УСПЕХА для вашего тестбенча!
    j end

fail:
    li gp, 3        # МАРКЕР ОШИБКИ (x3 = 3)

end:
    j end           # Бесконечный цикл

# =================================================================
# РЕКУРСИВНАЯ ФУНКЦИЯ towers(n, from, to, aux)
# =================================================================
towers:
    # Сохраняем контекст в стек (базовый пролог функции)
    addi sp, sp, -32
    sw   ra, 28(sp)   # Сохраняем адрес возврата
    sw   s0, 24(sp)
    sw   a0, 20(sp)   # Сохраняем текущее n
    sw   a1, 16(sp)   # Сохраняем from
    sw   a2, 12(sp)   # Сохраняем to
    sw   a3, 8(sp)    # Сохраняем aux

    # Базовый случай: если n == 1, просто перемещаем диск
    li   t0, 1
    beq  a0, t0, move_disk

    # --- РЕКУРСИВНЫЙ ШАГ 1: towers(n-1, from, aux, to) ---
    addi a0, a0, -1   # n = n - 1
    # Меняем местами аргументы 'to' и 'aux'
    mv   t0, a2       # t0 = to
    mv   a2, a3       # новый 'to' = старый 'aux'
    mv   a3, t0       # новый 'aux' = старый 'to'
    jal  ra, towers

    # Восстанавливаем аргументы из стека перед перемещением диска
    lw   a1, 16(sp)
    lw   a2, 12(sp)

move_disk:
    # --- СИМУЛЯЦИЯ ПЕРЕМЕЩЕНИЯ ДИСКА В РЕГИСТРАХ S1, S2, S3 ---
    # Уменьшаем количество дисков на стержне 'from' (a1)
    li   t0, 0
    beq  a1, t0, dec_s1
    li   t0, 1
    beq  a1, t0, dec_s2
    addi s3, s3, -1
    j    inc_target
dec_s1:
    addi s1, s1, -1
    j    inc_target
dec_s2:
    addi s2, s2, -1

inc_target:
    # Увеличиваем количество дисков на стержне 'to' (a2)
    li   t0, 0
    beq  a2, t0, inc_s1
    li   t0, 1
    beq  a2, t0, inc_s2
    addi s3, s3, 1
    j    check_base_case
inc_s1:
    addi s1, s1, 1
    j    check_base_case
inc_s2:
    addi s2, s2, 1

check_base_case:
    # Если это был базовый случай (n==1), то выходим из функции
    lw   a0, 20(sp)
    li   t0, 1
    beq  a0, t0, towers_epilogue

    # --- РЕКУРСИВНЫЙ ШАГ 2: towers(n-1, aux, to, from) ---
    # Восстанавливаем оригинальные значения, чтобы правильно перетасовать
    lw   a0, 20(sp)
    lw   a1, 16(sp)
    lw   a2, 12(sp)
    lw   a3, 8(sp)

    addi a0, a0, -1   # n = n - 1
    # Перемешиваем: новый 'from'=aux, новый 'to'=to, новый 'aux'=from
    mv   t0, a1       # t0 = from
    mv   a1, a3       # новый 'from' = оригинальный 'aux'
    mv   a3, t0       # новый 'aux' = оригинальный 'from'
    jal  ra, towers

towers_epilogue:
    # Восстанавливаем ra и sp (эпилог функции)
    lw   ra, 28(sp)
    lw   s0, 24(sp)
    addi sp, sp, 32
    ret
