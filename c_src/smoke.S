.section .text
.global _start

_start:
    # 1. Записываем маркер начала в x10 (a0)
    li  a0, 0xAAAA

    # 2. Инициализируем стек в конец 64 КБ памяти
    li  sp, 0xFFF0

    # 3. Делаем простейший цикл на 5 итераций
    li  t0, 5          # Счетчик цикла
    li  t1, 0          # Аккумулятор (сумматор)

loop:
    add t1, t1, t0     # t1 = t1 + t0
    addi t0, t0, -1    # t0 = t0 - 1
    bne t0, zero, loop # Если t0 != 0, прыгаем назад

    # Ожидаемый результат в t1: 5 + 4 + 3 + 2 + 1 = 15 (0xF)

    # 4. Проверяем результат работы цикла
    li  t2, 15
    bne t1, t2, fail   # Если сумма не 15, уходим на FAIL

    # 5. Тест пройден успешно! Записываем 1 в x3 (gp)
    li  gp, 1
    li  a0, 0x5555     # Маркер успеха в a0
    j   end

fail:
    li  gp, 3          # Маркер ошибки в x3 (gp)
    li  a0, 0xDEAD     # Маркер ошибки в a0

end:
    # Бесконечный цикл, чтобы процессор не выполнял мусор
    j   end
